class TestImplModule(unittest.TestCase):
    """Tests for render_impl_c_module."""

    @classmethod
    def setUpClass(cls):
        cls.pir = _foundation_ir()
        cls.root = render_impl_c_module(cls.pir)

    def test_impl_tag_enum_exists(self):
        enum = self.root.find(".//c_enum[@name='vscf_impl_tag_t']")
        self.assertIsNotNone(enum, "impl_tag enum must exist")

    def test_impl_tag_enum_has_begin_and_end(self):
        enum = self.root.find(".//c_enum[@name='vscf_impl_tag_t']")
        constants = enum.findall("c_constant")
        names = [c.attrib["name"] for c in constants]
        self.assertEqual(names[0], "vscf_impl_tag_BEGIN")
        self.assertEqual(names[-1], "vscf_impl_tag_END")
        self.assertEqual(constants[0].attrib["value"], "0")

    def test_impl_tag_enum_has_all_implementations(self):
        enum = self.root.find(".//c_enum[@name='vscf_impl_tag_t']")
        constants = enum.findall("c_constant")
        impl_constants = [c.attrib["name"] for c in constants[1:-1]]
        impl_names_from_ir = sorted(i.name for i in self.pir.implementations)
        expected = [f"vscf_impl_tag_{n.replace(' ', '_').upper()}" for n in impl_names_from_ir]
        self.assertEqual(impl_constants, expected)
        self.assertEqual(len(impl_constants), 58)

    def test_impl_tag_enum_sorted_alphabetically(self):
        enum = self.root.find(".//c_enum[@name='vscf_impl_tag_t']")
        constants = enum.findall("c_constant")
        impl_names = [c.attrib["name"] for c in constants[1:-1]]
        # The generator orders the enum by the sorted IR implementation names
        # (space-separated, lower-case: see project_c_backend `sorted(i.name ...)`),
        # then transforms each to the vscf_impl_tag_<UPPER_UNDERSCORE> constant.
        # Re-sorting the *transformed* strings would use a different key: for
        # adjacent names like "chunk cipher"/"chunked alg info", ' ' (0x20) sorts
        # before 'e' whereas '_' (0x5F) sorts after 'E', flipping the order. So
        # compare against the IR-name sort key the generator actually uses.
        expected = [
            f"vscf_impl_tag_{n.replace(' ', '_').upper()}"
            for n in sorted(i.name for i in self.pir.implementations)
        ]
        self.assertEqual(impl_names, expected)

    def test_impl_t_forward_declaration(self):
        struct = self.root.find(".//c_struct[@name='vscf_impl_t']")
        self.assertIsNotNone(struct, "impl_t struct must exist")
        self.assertEqual(struct.attrib["declaration"], "public")
        self.assertEqual(struct.attrib["definition"], "external")

    def test_dispatch_methods_present(self):
        methods = self.root.findall(".//c_method")
        method_names = {m.attrib["name"] for m in methods}
        expected = {
            "vscf_impl_api",
            "vscf_impl_tag",
            "vscf_impl_cleanup",
            "vscf_impl_delete",
            "vscf_impl_destroy",
            "vscf_impl_shallow_copy",
            "vscf_impl_shallow_copy_const",
        }
        self.assertEqual(method_names, expected)

    def test_dispatch_method_api_has_code(self):
        method = self.root.find(".//c_method[@name='vscf_impl_api']")
        code = method.find("c_code")
        self.assertIsNotNone(code, "api method must have generated code")
        self.assertIn("find_api_cb", code.text)

    def test_dispatch_method_tag_has_code(self):
        method = self.root.find(".//c_method[@name='vscf_impl_tag']")
        code = method.find("c_code")
        self.assertIn("impl_tag", code.text)

    def test_dispatch_method_cleanup_has_code(self):
        method = self.root.find(".//c_method[@name='vscf_impl_cleanup']")
        code = method.find("c_code")
        self.assertIn("self_cleanup_cb", code.text)

    def test_dispatch_method_delete_has_code(self):
        method = self.root.find(".//c_method[@name='vscf_impl_delete']")
        code = method.find("c_code")
        self.assertIn("self_delete_cb", code.text)

    def test_dispatch_method_destroy_has_code(self):
        method = self.root.find(".//c_method[@name='vscf_impl_destroy']")
        code = method.find("c_code")
        self.assertIn("impl_delete", code.text)

    def test_dispatch_method_shallow_copy_has_code(self):
        method = self.root.find(".//c_method[@name='vscf_impl_shallow_copy']")
        code = method.find("c_code")
        self.assertIn("ATOMIC_COMPARE_EXCHANGE_WEAK", code.text)

    def test_dispatch_method_shallow_copy_const_has_code(self):
        method = self.root.find(".//c_method[@name='vscf_impl_shallow_copy_const']")
        code = method.find("c_code")
        self.assertIn("shallow_copy", code.text)

    def test_includes(self):
        includes = [inc.attrib["file"] for inc in self.root.findall("c_include")]
        self.assertIn("vscf_library.h", includes)
        self.assertIn("vscf_api.h", includes)

    def test_private_includes(self):
        private_includes = [inc.attrib["file"] for inc in self.root.findall("c_include[@scope='private']")]
        self.assertIn("vscf_impl_private.h", private_includes)
        self.assertIn("vscf_assert.h", private_includes)
        self.assertIn("vscf_atomic.h", private_includes)


