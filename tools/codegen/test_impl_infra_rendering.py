class TestCommonProjectNoInfra(unittest.TestCase):
    """Common project has no interfaces/implementations; no infra modules should appear."""

    def test_no_impl_infra_in_common(self):
        renderers = direct_c_renderers_for_project("common", ".")
        for key in renderers:
            self.assertNotIn("vscf_api", key, f"common should not have impl infrastructure: {key}")
            self.assertNotIn("vscf_impl", key, f"common should not have impl infrastructure: {key}")

    def test_common_has_no_interfaces(self):
        pir = _common_ir()
        self.assertEqual(len(pir.interfaces), 0)
        self.assertEqual(len(pir.implementations), 0)


