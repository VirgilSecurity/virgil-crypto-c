class TestApiModule(unittest.TestCase):
    """Tests for render_api_c_module."""

    @classmethod
    def setUpClass(cls):
        cls.pir = _foundation_ir()
        cls.root = render_api_c_module(cls.pir)

    def test_root_element(self):
        self.assertEqual(self.root.tag, "c_module")
        self.assertEqual(self.root.attrib["name"], "vscf_api")
        self.assertEqual(self.root.attrib["scope"], "public")

    def test_api_tag_enum_exists(self):
        enum = self.root.find(".//c_enum[@name='vscf_api_tag_t']")
        self.assertIsNotNone(enum, "api_tag enum must exist")

    def test_api_tag_enum_has_begin_and_end(self):
        enum = self.root.find(".//c_enum[@name='vscf_api_tag_t']")
        constants = enum.findall("c_constant")
        names = [c.attrib["name"] for c in constants]
        self.assertEqual(names[0], "vscf_api_tag_BEGIN")
        self.assertEqual(names[-1], "vscf_api_tag_END")
        # BEGIN has value 0
        self.assertEqual(constants[0].attrib["value"], "0")

    def test_api_tag_enum_has_all_interfaces(self):
        enum = self.root.find(".//c_enum[@name='vscf_api_tag_t']")
        constants = enum.findall("c_constant")
        # Exclude BEGIN and END
        iface_constants = [c.attrib["name"] for c in constants[1:-1]]
        iface_names_from_ir = sorted(i.name for i in self.pir.interfaces)
        expected = [f"vscf_api_tag_{n.replace(' ', '_').upper()}" for n in iface_names_from_ir]
        self.assertEqual(iface_constants, expected)
        # Must match the reference count (34 interfaces)
        self.assertEqual(len(iface_constants), 34)

    def test_api_tag_enum_sorted_alphabetically(self):
        enum = self.root.find(".//c_enum[@name='vscf_api_tag_t']")
        constants = enum.findall("c_constant")
        iface_names = [c.attrib["name"] for c in constants[1:-1]]
        self.assertEqual(iface_names, sorted(iface_names))

    def test_api_t_forward_declaration(self):
        struct = self.root.find(".//c_struct[@name='vscf_api_t']")
        self.assertIsNotNone(struct, "api_t struct must exist")
        self.assertEqual(struct.attrib["declaration"], "public")
        self.assertEqual(struct.attrib["definition"], "external")

    def test_includes_library(self):
        includes = [inc.attrib["file"] for inc in self.root.findall("c_include")]
        self.assertIn("vscf_library.h", includes)


