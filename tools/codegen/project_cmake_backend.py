def generate_definitions_cmake(project_ir: IRProject, license_text: str = "") -> str:
    """Generate ``definitions.cmake`` content for a project."""
    PREFIX = project_ir.prefix.upper()
    lines: list[str] = []

    lines.append(_cmake_prologue(license_text))
    lines.append("")
    lines.append(_target_check(project_ir.name))
    lines.append("")
    lines.append(f"target_compile_definitions({project_ir.name}")
    lines.append("        PUBLIC")
    lines.append(f"            $<BUILD_INTERFACE:{PREFIX}_INTERNAL_BUILD>")
    lines.append(f'            "{PREFIX}_SHARED_LIBRARY=$<BOOL:${{BUILD_SHARED_LIBS}}>"')

    for flag, _desc in _collect_feature_entities(project_ir):
        lines.append(f'            "{flag}=$<BOOL:${{{flag}}}>"')

    lines.append("        )")
    lines.append("")
    return "\n".join(lines)


