"""CMake file generation for the project-rooted codegen pipeline.

Generates three CMake files per project:
- ``definitions.cmake`` — compile definitions with feature flags
- ``features.cmake`` — feature option declarations and dependency checks
- ``sources.cmake`` — source file listings, include directories, Apple framework properties

All generation is model-driven from ``IRProject`` — no per-project branching.
"""
from __future__ import annotations

from typing import cast

from tools.codegen.project_c_backend import (
    IRClass,
    IREnum,
    IRImplementation,
    IRInterface,
    IROutputTarget,
    IRProject,
    class_defs_output,
    implementation_defs_output,
    implementation_internal_output,
    implementation_private_output,
    interface_api_output,
    snake_name,
)
from tools.codegen.project_ir import IRExternalLibrary, IRFeatureRequire
from tools.codegen.project_ir import IRFeature


