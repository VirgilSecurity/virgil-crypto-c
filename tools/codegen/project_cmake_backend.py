def generate_cmake_files(project_ir: IRProject, license_text: str = "") -> list[tuple[str, str]]:
    """Generate all three CMake files for a project.

    Returns a list of (relative_path, content) tuples where the path is
    relative to the repo root (e.g. ``library/ratchet/sources.cmake``).
    """
    project_path = project_ir.attrs.get("path", f"../library/{project_ir.name}")
    # Normalize: ../library/ratchet → library/ratchet/
    if project_path.startswith("../"):
        project_path = project_path[3:]
    if not project_path.endswith("/"):
        project_path += "/"

    return [
        (f"{project_path}sources.cmake", generate_sources_cmake(project_ir, license_text)),
        (f"{project_path}features.cmake", generate_features_cmake(project_ir, license_text)),
        (f"{project_path}definitions.cmake", generate_definitions_cmake(project_ir, license_text)),
    ]


