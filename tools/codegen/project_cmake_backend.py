def feature_flag_name(prefix: str, entity_name: str) -> str:
    """Derive the CMake feature flag from a project prefix and entity name.

    E.g. ``feature_flag_name("vscr", "ratchet session")`` → ``"VSCR_RATCHET_SESSION"``.
    """
    return f"{prefix.upper()}_{snake_name(entity_name).upper()}"


def _cmake_license_block(license_text: str) -> str:
    if not license_text:
        return ""
    lines = ["#   @license", "#   " + "-" * 73]
    for line in license_text.strip().splitlines():
        line = line.strip()
        lines.append(f"#   {line}" if line else "#")
    lines.append("#   " + "-" * 73)
    return "\n".join(lines)


def _cmake_prologue(license_text: str) -> str:
    """Return the standard prologue: license + warning + include_guard."""
    parts: list[str] = []
    lic = _cmake_license_block(license_text)
    if lic:
        parts.append(lic)
    parts.append("")
    parts.append("#   @warning")
    parts.append("#   " + "-" * 73)
    parts.append("#   This file is fully generated by script 'cmake_files_codegen.gsl'.")
    parts.append("#   It can be changed temporary for debug purposes only.")
    parts.append("#   " + "-" * 73)
    parts.append("#   @end")
    parts.append("")
    parts.append("")
    parts.append("include_guard()")
    return "\n".join(parts)


def _target_check(project_name: str) -> str:
    return (
        f"if(NOT TARGET {project_name})\n"
        f'    message(FATAL_ERROR "Expected target \'{project_name}\' to be defined first.")\n'
        f"endif()"
    )


def _collect_feature_entities(project_ir: IRProject) -> list[tuple[str, str]]:
    """Collect (feature_flag, description) pairs for all feature-bearing entities.

    Returns them in project-XML order: LIBRARY, project features, classes,
    interfaces, implementations.
    """
    prefix = project_ir.prefix
    PREFIX = prefix.upper()
    entries: list[tuple[str, str]] = []

    # LIBRARY is always first
    entries.append((f"{PREFIX}_LIBRARY", f"Enable build of the '{project_ir.name}' library"))

    # Project-level features (e.g. multi_threading)
    for feat in project_ir.features:
        entries.append((feature_flag_name(prefix, feat.name), feat.description or f"Enable feature '{feat.name}'."))

    # Classes
    for cls in project_ir.classes:
        entries.append((feature_flag_name(prefix, cls.name), f"Enable class '{cls.name}'."))

    # Interfaces
    for iface in project_ir.interfaces:
        entries.append((feature_flag_name(prefix, iface.name), f"Enable interface '{iface.name}'."))

    # Implementations
    for impl in project_ir.implementations:
        entries.append((feature_flag_name(prefix, impl.name), f"Enable implementation '{impl.name}'."))

    return entries


