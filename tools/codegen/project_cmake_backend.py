def _resolve_requirement_feature(
    req_kind: str,
    req_name: str,
    req_project: str | None,
    *,
    project_ir: IRProject,
) -> str | None:
    """Resolve a requirement to its CMake feature flag name.

    Returns None if the requirement doesn't map to a feature (e.g. header requires).
    """
    # Determine the prefix for the target project
    if req_project:
        target_prefix = None
        for fp in getattr(project_ir, 'fallback_projects', None) or []:
            if fp.name == req_project:
                target_prefix = fp.prefix
                break
        if target_prefix is None:
            # Static fallback
            prefix_map = {"common": "vsc", "foundation": "vscf", "ratchet": "vscr", "phe": "vsce"}
            target_prefix = prefix_map.get(req_project, req_project)
    else:
        target_prefix = project_ir.prefix

    if req_kind in ("class", "impl", "interface"):
        return feature_flag_name(target_prefix, req_name)
    elif req_kind == "feature":
        return feature_flag_name(target_prefix, req_name)
    elif req_kind == "module":
        # Modules don't have feature flags — they're unconditional
        return None
    return None


def generate_features_cmake(project_ir: IRProject, license_text: str = "") -> str:
    """Generate ``features.cmake`` content for a project."""
    lines: list[str] = []

    lines.append(_cmake_prologue(license_text))
    lines.append("")

    entities = _collect_feature_entities(project_ir)

    # option() declarations
    for flag, desc in entities:
        lines.append(f'option({flag} "{desc}" ON)')

    # mark_as_advanced()
    lines.append("mark_as_advanced(")
    for flag, _desc in entities:
        lines.append(f"        {flag}")
    lines.append("        )")
    lines.append("")

    # Dependency checks — iterate classes, interfaces, implementations
    def _emit_dep_checks(entity_name: str, requirements: list) -> None:
        source_flag = feature_flag_name(project_ir.prefix, entity_name)
        for req in requirements:
            dep_flag = _resolve_requirement_feature(
                req.kind, req.name, req.attrs.get("project"),
                project_ir=project_ir,
            )
            if dep_flag is None or dep_flag == source_flag:
                continue
            if req.attrs.get("is_optional") == "1":
                continue
            lines.append(f"if({source_flag} AND NOT {dep_flag})")
            lines.append('    message("-- error --")')
            lines.append('    message("--")')
            lines.append(f'    message("Feature {source_flag} depends on the feature:")')
            lines.append(f'    message("     {dep_flag} - which is disabled.")')
            lines.append('    message("--")')
            lines.append("    message(FATAL_ERROR)")
            lines.append("endif()")
            lines.append("")

    for cls in project_ir.classes:
        _emit_dep_checks(cls.name, cls.requirements)

    for iface in project_ir.interfaces:
        _emit_dep_checks(iface.name, getattr(iface, 'requirements', []))

    for impl in project_ir.implementations:
        _emit_dep_checks(impl.name, impl.requirements)

    return "\n".join(lines)


