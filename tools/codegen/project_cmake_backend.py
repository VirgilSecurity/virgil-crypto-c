def _cmake_path(header_path: str, project_ir: IRProject) -> str:
    """Convert a repo-relative header/source path to a CMake path expression.

    E.g. ``../library/ratchet/include/virgil/crypto/ratchet/vscr_assert.h``
    → ``${CMAKE_CURRENT_LIST_DIR}/include/virgil/crypto/ratchet/vscr_assert.h``
    """
    # The paths from IROutputTarget are relative to the codegen root
    # (e.g. ../library/ratchet/...). We need them relative to library/{project}/
    project_path = project_ir.attrs.get("path", f"../library/{project_ir.name}")
    if not project_path.endswith("/"):
        project_path += "/"
    if header_path.startswith(project_path):
        rel = header_path[len(project_path):]
    elif header_path.startswith(f"../library/{project_ir.name}/"):
        rel = header_path[len(f"../library/{project_ir.name}/"):]
    else:
        rel = header_path
    return f"${{CMAKE_CURRENT_LIST_DIR}}/{rel}"


def _is_unconditional_entity(entity_kind: str, entity_name: str, attrs: dict) -> bool:
    """Determine if an entity is unconditional (no feature guard) in sources.cmake."""
    # Shared modules are unconditional
    if entity_kind == "module":
        return True
    # Enums are unconditional
    if entity_kind == "enum":
        return True
    return False


def _impl_has_private_methods(impl: IRImplementation) -> bool:
    for method in impl.methods:
        scope = method.attrs.get("scope", "")
        decl = method.attrs.get("declaration", "private")
        if scope == "private" and decl == "public":
            return True
    return False


def generate_sources_cmake(project_ir: IRProject, license_text: str = "") -> str:
    """Generate ``sources.cmake`` content for a project."""
    PREFIX = project_ir.prefix.upper()
    ns = project_ir.include_namespace  # e.g. "virgil/crypto/ratchet"
    lines: list[str] = []

    lines.append(_cmake_prologue(license_text))
    lines.append("")
    lines.append(_target_check(project_ir.name))
    lines.append("")

    # Platform checks
    lines.append("include(CheckIncludeFiles)")
    lines.append(f"check_include_files(assert.h {PREFIX}_HAVE_ASSERT_H)")
    lines.append(f"check_include_files(stdatomic.h {PREFIX}_HAVE_STDATOMIC_H)")
    lines.append("")

    # configure_file for platform.h.in
    has_platform = any(
        m.attrs.get("has_cmakedefine") == "1" or "platform" in m.name
        for m in project_ir.modules + project_ir.dependency_modules
    )
    if has_platform:
        lines.append("configure_file(")
        lines.append(f'        "${{CMAKE_CURRENT_LIST_DIR}}/include/{ns}/{project_ir.prefix}_platform.h.in"')
        lines.append(f'        "${{CMAKE_CURRENT_BINARY_DIR}}/include/{ns}/{project_ir.prefix}_platform.h"')
        lines.append("        )")
        lines.append("")

    # Collect all files grouped by: unconditional headers, featured headers, unconditional sources, featured sources
    uncond_headers: list[str] = []
    uncond_sources: list[str] = []
    featured_headers: list[tuple[str, str]] = []  # (feature_flag, path)
    featured_sources: list[tuple[str, str]] = []
    public_headers: list[str] = []  # For MACOSX_PACKAGE_LOCATION

    def _add_output(output: IROutputTarget, feature: str | None, *, has_defs: bool = False, defs_output: IROutputTarget | None = None) -> None:
        header_cmake = _cmake_path(output.header_path, project_ir)
        source_cmake = _cmake_path(output.source_path, project_ir)
        if output.header_visibility == "public":
            public_headers.append(header_cmake)

        if feature:
            featured_headers.append((feature, header_cmake))
            featured_sources.append((feature, source_cmake))
            if has_defs and defs_output:
                defs_h = _cmake_path(defs_output.header_path, project_ir)
                defs_c = _cmake_path(defs_output.source_path, project_ir)
                featured_headers.append((feature, defs_h))
                featured_sources.append((feature, defs_c))
        else:
            uncond_headers.append(header_cmake)
            uncond_sources.append(source_cmake)

    # Modules (unconditional)
    all_modules = project_ir.modules + project_ir.dependency_modules
    for mod in all_modules:
        output = cast(IROutputTarget, mod.output)
        if mod.attrs.get("has_cmakedefine") == "1":
            # Platform module: header comes from configure_file, no .c source
            # The .h.in is listed as a header, configured .h added separately below
            uncond_headers.append(f"${{CMAKE_CURRENT_LIST_DIR}}/include/{ns}/{project_ir.prefix}_{snake_name(mod.name)}.h.in")
        else:
            _add_output(output, None)

    # Platform header (configured, unconditional)
    if has_platform:
        platform_h = f"${{CMAKE_CURRENT_BINARY_DIR}}/include/{ns}/{project_ir.prefix}_platform.h"
        uncond_headers.append(platform_h)
        public_headers.append(platform_h)

    # Enums (unconditional)
    for enum in project_ir.enums:
        output = cast(IROutputTarget, enum.output)
        _add_output(output, None)

    # Classes (feature-gated)
    for cls in project_ir.classes:
        output = cast(IROutputTarget, cls.output)
        flag = feature_flag_name(project_ir.prefix, cls.name)
        # Determine if class has a separate _defs module
        is_value_type = cls.attrs.get("is_value_type") in {"1", "true"}
        context = cls.attrs.get("context", "public")
        cls_scope = cls.attrs.get("scope", "public")
        has_lifecycle = cls.attrs.get("lifecycle") != "none"
        inline_struct = is_value_type or not has_lifecycle or (cls_scope == "internal" and context == "public")
        has_defs = not inline_struct and context != "none"
        defs_out = class_defs_output(output, context=context, scope=cls_scope) if has_defs else None
        _add_output(output, flag, has_defs=has_defs, defs_output=defs_out)

    # Interfaces (feature-gated) — dispatch module + API module
    for iface in project_ir.interfaces:
        iface_output = cast(IROutputTarget, iface.output)
        flag = feature_flag_name(project_ir.prefix, iface.name)
        iface_h = _cmake_path(iface_output.header_path, project_ir)
        # Dispatch module (main) — public header for framework packaging
        featured_headers.append((flag, iface_h))
        featured_sources.append((flag, _cmake_path(iface_output.source_path, project_ir)))
        if iface_output.header_visibility == "public":
            public_headers.append(iface_h)
        # API module (private header — not in framework)
        api_out = interface_api_output(iface_output)
        featured_headers.append((flag, _cmake_path(api_out.header_path, project_ir)))
        featured_sources.append((flag, _cmake_path(api_out.source_path, project_ir)))

    # Implementations (feature-gated) — main + defs + internal [+ private]
    for impl in project_ir.implementations:
        impl_output = cast(IROutputTarget, impl.output)
        flag = feature_flag_name(project_ir.prefix, impl.name)
        impl_h = _cmake_path(impl_output.header_path, project_ir)
        # Main module — public header for framework packaging
        featured_headers.append((flag, impl_h))
        featured_sources.append((flag, _cmake_path(impl_output.source_path, project_ir)))
        if impl_output.header_visibility == "public":
            public_headers.append(impl_h)
        # Defs module
        defs_out = implementation_defs_output(impl_output)
        featured_headers.append((flag, _cmake_path(defs_out.header_path, project_ir)))
        featured_sources.append((flag, _cmake_path(defs_out.source_path, project_ir)))
        # Internal module
        internal_out = implementation_internal_output(impl_output)
        featured_headers.append((flag, _cmake_path(internal_out.header_path, project_ir)))
        featured_sources.append((flag, _cmake_path(internal_out.source_path, project_ir)))
        # Private module (when impl has scope="private" methods)
        if _impl_has_private_methods(impl):
            private_out = implementation_private_output(impl_output)
            featured_headers.append((flag, _cmake_path(private_out.header_path, project_ir)))

    # Infrastructure files (unconditional when project has interfaces)
    # These are auto-generated by the C backend for projects with interfaces/implementations.
    if project_ir.interfaces:
        prefix = project_ir.prefix
        # api module: generic API type infrastructure
        uncond_headers.append(f"${{CMAKE_CURRENT_LIST_DIR}}/include/{ns}/{prefix}_api.h")
        public_headers.append(f"${{CMAKE_CURRENT_LIST_DIR}}/include/{ns}/{prefix}_api.h")
        uncond_headers.append(f"${{CMAKE_CURRENT_LIST_DIR}}/include/{ns}/private/{prefix}_api_private.h")
        uncond_sources.append(f"${{CMAKE_CURRENT_LIST_DIR}}/src/{prefix}_api.c")
        uncond_sources.append(f"${{CMAKE_CURRENT_LIST_DIR}}/src/{prefix}_api_private.c")
        # impl private module
        uncond_headers.append(f"${{CMAKE_CURRENT_LIST_DIR}}/include/{ns}/private/{prefix}_impl_private.h")

    # Umbrella headers (unconditional, public for framework packaging)
    pub_umbrella = f"${{CMAKE_CURRENT_LIST_DIR}}/include/{ns}/{project_ir.prefix}_{project_ir.name}_public.h"
    uncond_headers.append(pub_umbrella)
    public_headers.append(pub_umbrella)
    uncond_headers.append(f"${{CMAKE_CURRENT_LIST_DIR}}/include/{ns}/private/{project_ir.prefix}_{project_ir.name}_private.h")

    # MACOSX_PACKAGE_LOCATION for public headers
    for h in public_headers:
        lines.append("set_property(")
        lines.append(f'    SOURCE "{h}"')
        lines.append('    PROPERTY MACOSX_PACKAGE_LOCATION "Headers"')
        lines.append(")")
        lines.append("")

    # target_sources()
    lines.append(f"target_sources({project_ir.name}")
    lines.append("    PRIVATE")

    # Unconditional headers
    for h in uncond_headers:
        lines.append(f'            "{h}"')

    # Featured headers
    for flag, h in featured_headers:
        lines.append(f'            "$<$<BOOL:${{{flag}}}>:{h}>"')

    # Blank line between headers and sources
    lines.append("")

    # Unconditional sources
    for s in uncond_sources:
        lines.append(f'            "{s}"')

    # Featured sources
    for flag, s in featured_sources:
        lines.append(f'            "$<$<BOOL:${{{flag}}}>:{s}>"')

    lines.append("        )")
    lines.append("")

    # target_include_directories()
    lines.append(f"target_include_directories({project_ir.name}")
    lines.append("        PUBLIC")
    lines.append(f"            $<BUILD_INTERFACE:${{CMAKE_CURRENT_LIST_DIR}}/include>")
    lines.append(f"            $<BUILD_INTERFACE:${{CMAKE_CURRENT_LIST_DIR}}/include/{ns}>")
    lines.append(f"            $<BUILD_INTERFACE:${{CMAKE_CURRENT_LIST_DIR}}/include/{ns}/private>")
    lines.append(f"            $<BUILD_INTERFACE:${{CMAKE_CURRENT_BINARY_DIR}}/include/{ns}>")
    lines.append(f"            $<BUILD_INTERFACE:${{CMAKE_CURRENT_BINARY_DIR}}/include/{ns}/private>")
    lines.append(f"            $<BUILD_INTERFACE:${{CMAKE_CURRENT_LIST_DIR}}/src>")
    lines.append(f"            $<INSTALL_INTERFACE:${{CMAKE_INSTALL_INCLUDEDIR}}>")
    lines.append("        )")
    lines.append("")
    return "\n".join(lines)


